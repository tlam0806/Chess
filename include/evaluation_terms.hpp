constexpr const std::array<int, 64>& evaluation_piece_square_table(PieceType piece) {
    switch (piece) {
        case PieceType::Pawn:
            return PawnPst;
        case PieceType::Knight:
            return KnightPst;
        case PieceType::Bishop:
            return BishopPst;
        case PieceType::Rook:
            return RookPst;
        case PieceType::Queen:
            return QueenPst;
        case PieceType::King:
            return KingPst;
        default:
            return KingPst;
    }
}

constexpr int evaluation_piece_contribution(Color color, PieceType piece, Square square) {
    assert(piece != PieceType::None);
    const int piece_idx = static_cast<int>(piece);
    const Square pst_square = relative_square(color, square);
    const int score = EvaluationPieceValue[piece_idx] + evaluation_piece_square_table(piece)[pst_square];
    return color == Color::White ? score : -score;
}

